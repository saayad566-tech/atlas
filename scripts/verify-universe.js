// Plain-node verification of the cross-sectional layer.
const fs=require('fs'),os=require('os'),path=require('path');
const { openDatabase } = require('../dist/finance/core/db');
const { ingestFixture } = require('../dist/finance/core/ingest');
const U = require('../dist/finance/core/universe');
let fails=0; const ok=(n,c,d)=>{ if(!c) fails++; console.log(`  ${c?'PASS':'FAIL'}  ${n}${d?'  — '+d:''}`); };
const db=openDatabase(path.join(fs.mkdtempSync(path.join(os.tmpdir(),'vu-')),'u.db'));
ingestFixture(db.db,{companies:30,seed:31});
const syms=db.db.prepare('SELECT symbol FROM companies ORDER BY id LIMIT 6').all().map(r=>r.symbol);
console.log('=== UNIVERSE ===');
const cov=U.coverageReport(db.db);
ok('coverage report', cov.companies===30 && cov.pct.prices===100, `${cov.companies} companies, prices ${cov.pct.prices}%`);
const br=U.breadth2(db.db);
ok('breadth advancers/decliners', br.total>0, `${br.advancers} up / ${br.decliners} down (${br.pctAdvancing}% advancing)`);
const rot=U.sectorRotation(db.db);
ok('sector rotation', rot.length>0, rot.slice(0,2).map(s=>`${s.sector} ${s.m1}%`).join(' | '));
const fr=U.freshness(db.db);
ok('freshness flags', fr.length===30, `${fr.filter(f=>f.stale).length} stale`);
const cm=U.correlationMatrix(db.db,syms.slice(0,4));
ok('correlation matrix', cm.matrix.length===4 && cm.matrix[0][0]===1, `r(0,1)=${cm.matrix[0][1]}`);
const rp=U.riskProfile(db.db,syms[0]);
ok('risk profile', rp!==null && rp.sharpe!==null, `sharpe ${rp.sharpe}, vol ${rp.annualVolPct}%, recovery ${rp.recoveryDays}d`);
const inv=U.investability(db.db,syms[0]);
ok('investability score', inv!==null, `${inv.score} (${inv.grade})`);
const cmp=U.compare(db.db,syms.slice(0,3));
ok('comparison rows', cmp.length===3, cmp.map(c=>`${c.symbol}:${c.investability}`).join(' '));
const pa=U.portfolioAnalytics(db.db,[{symbol:syms[0],value:100000,sector:'A'},{symbol:syms[1],value:50000,sector:'B'}]);
ok('portfolio analytics', pa.hhi>0, `HHI ${pa.hhi} (${pa.concentration}), vol ${pa.weightedVolPct}%`);
const wd=U.watchlistDigest(db.db,syms.slice(0,3));
ok('watchlist digest', wd.length===3, wd.map(w=>`${w.symbol}:${w.investability}`).join(' '));
console.log(fails===0?'\nUNIVERSE CHECKS PASSED':`\n${fails} FAILED`);
process.exit(fails===0?0:1);
